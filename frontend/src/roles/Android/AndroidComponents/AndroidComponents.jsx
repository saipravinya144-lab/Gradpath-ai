const shuffleArray = (array) => {
  const shuffled = [...array];

  for (let i = shuffled.length - 1; i > 0; i--) {
    const randomIndex = Math.floor(Math.random() * (i + 1));

    [shuffled[i], shuffled[randomIndex]] = [
      shuffled[randomIndex],
      shuffled[i],
    ];
  }

  return shuffled;
};

const AndroidComponents = ({ goBack }) => {
  const [activeTopicIndex, setActiveTopicIndex] = useState(0);
  const { completed, markComplete: saveProgress } = useLearningProgress("android-androidcomponents", subtopics);
  const [quizStarted, setQuizStarted] = useState(false);
  const [questionIndex, setQuestionIndex] = useState(0);
  const [selectedAnswer, setSelectedAnswer] = useState(null);
  const [submitted, setSubmitted] = useState(false);
  const [score, setScore] = useState(0);

  const [shuffledQuizOptions] = useState(() => {
    const shuffled = {};

    subtopics.forEach((topic) => {
      const quiz = topic?.lesson?.quiz || [];

      shuffled[topic.id] = quiz.map((question) =>
        shuffleArray(question?.options || [])
      );
    });

    return shuffled;
  });

  const activeTopic = subtopics[activeTopicIndex];

  const quizQuestions = activeTopic?.lesson?.quiz || [];

  const currentQuestion =
    quizQuestions[questionIndex] || quizQuestions[0];

  const options =
    activeTopic && shuffledQuizOptions[activeTopic.id]
      ? shuffledQuizOptions[activeTopic.id][questionIndex] || []
      : [];

  const openTopic = (index) => {
    setActiveTopicIndex(index);
    setQuizStarted(false);
    setQuestionIndex(0);
    setSelectedAnswer(null);
    setSubmitted(false);
    setScore(0);
  };

  const markCompleted = () => {
    if (!activeTopic) return;
    saveProgress(activeTopic.id);
  };

  const startQuiz = () => {
    if (!currentQuestion || quizQuestions.length === 0) {
      return;
    }

    setQuizStarted(true);
    setQuestionIndex(0);
    setSelectedAnswer(null);
    setSubmitted(false);
    setScore(0);
  };

  const submitAnswer = () => {
    if (!selectedAnswer || submitted || !currentQuestion) {
      return;
    }

    setSubmitted(true);

    if (selectedAnswer === currentQuestion.answer) {
      setScore((prev) => prev + 1);
    }
  };

  const nextQuestion = async () => {
    if (!currentQuestion) {
      return;
    }

    if (questionIndex < quizQuestions.length - 1) {
      setQuestionIndex((prev) => prev + 1);
      setSelectedAnswer(null);
      setSubmitted(false);
    } else {
      const finalScore = score;

      await saveQuizResult({
        subject: "Android Developer",
        role: "Android Developer",
        topic: activeTopic.title,
        topicId: activeTopic.id,
        score: finalScore,
        totalQuestions: quizQuestions.length
      });

      markCompleted();
      setQuizStarted(false);
      setQuestionIndex(0);
      setSelectedAnswer(null);
      setSubmitted(false);
    }
  };

  const getOptionStyle = (option) => {
    if (!submitted) {
      return {
        background:
          selectedAnswer === option ? "#dbeafe" : "white",
        border:
          selectedAnswer === option
            ? "2px solid #2563eb"
            : "1px solid #d1d5db",
        color: "#111827",
      };
    }

    if (
      currentQuestion &&
      option === currentQuestion.answer
    ) {
      return {
        background: "#dcfce7",
        border: "2px solid #16a34a",
        color: "#166534",
      };
    }

    if (
      option === selectedAnswer &&
      currentQuestion &&
      selectedAnswer !== currentQuestion.answer
    ) {
      return {
        background: "#fee2e2",
        border: "2px solid #dc2626",
        color: "#991b1b",
      };
    }

    return {
      background: "white",
      border: "1px solid #d1d5db",
      color: "#111827",
    };
  };

  if (!activeTopic) {
    return (
      <div
        style={{
          minHeight: "100vh",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          fontFamily: "Arial, sans-serif",
        }}
      >
        <p>Unable to load Android Components.</p>
      </div>
    );
  }

  if (quizStarted && currentQuestion) {
    return (
      <div
        style={{
          minHeight: "100vh",
          background:
            "linear-gradient(135deg, #eef6ff, #ffffff)",
          padding: "40px 20px",
          fontFamily: "Arial, sans-serif",
        }}
      >
        <div
          style={{
            maxWidth: "800px",
            margin: "0 auto",
            background: "white",
            borderRadius: "18px",
            padding: "32px",
            boxShadow: "0 8px 25px rgba(0,0,0,0.08)",
          }}
        >
          <button
            onClick={() => setQuizStarted(false)}
            style={{
              background: "transparent",
              border: "none",
              color: "#2563eb",
              cursor: "pointer",
              fontSize: "15px",
              marginBottom: "20px",
            }}
          >
            ← Back to Lesson
          </button>

          <h1
            style={{
              color: "#1e3a8a",
              marginBottom: "8px",
            }}
          >
            🧩 {activeTopic.title} Quiz
          </h1>

          <p style={{ color: "#6b7280" }}>
            Question {questionIndex + 1} of{" "}
            {quizQuestions.length}
          </p>

          <div
            style={{
              height: "8px",
              background: "#e5e7eb",
              borderRadius: "10px",
              overflow: "hidden",
              margin: "20px 0 30px",
            }}
          >
            <div
              style={{
                width: `${
                  ((questionIndex + 1) /
                    quizQuestions.length) *
                  100
                }%`,
                height: "100%",
                background: "#2563eb",
              }}
            />
          </div>

          <h2
            style={{
              fontSize: "22px",
              color: "#111827",
              marginBottom: "24px",
            }}
          >
            {currentQuestion.question}
          </h2>

          <div
            style={{
              display: "grid",
              gap: "12px",
            }}
          >
            {options.map((option, index) => (
              <button
                key={`${option}-${index}`}
                onClick={() =>
                  !submitted &&
                  setSelectedAnswer(option)
                }
                style={{
                  ...getOptionStyle(option),
                  padding: "15px 18px",
                  borderRadius: "10px",
                  textAlign: "left",
                  cursor: submitted
                    ? "default"
                    : "pointer",
                  fontSize: "16px",
                }}
              >
                {option}
              </button>
            ))}
          </div>

          {submitted &&
            selectedAnswer !== currentQuestion.answer && (
              <p
                style={{
                  marginTop: "20px",
                  color: "#166534",
                  fontWeight: "bold",
                }}
              >
                Correct answer:{" "}
                {currentQuestion.answer}
              </p>
            )}

          {submitted &&
            selectedAnswer === currentQuestion.answer && (
              <p
                style={{
                  marginTop: "20px",
                  color: "#166534",
                  fontWeight: "bold",
                }}
              >
                ✅ Correct answer!
              </p>
            )}

          {!submitted ? (
            <button
              onClick={submitAnswer}
              disabled={!selectedAnswer}
              style={{
                marginTop: "28px",
                width: "100%",
                padding: "14px",
                borderRadius: "10px",
                border: "none",
                background: selectedAnswer
                  ? "#2563eb"
                  : "#93c5fd",
                color: "white",
                fontSize: "16px",
                fontWeight: "bold",
                cursor: selectedAnswer
                  ? "pointer"
                  : "not-allowed",
              }}
            >
              Submit Answer
            </button>
          ) : (
            <button
              onClick={nextQuestion}
              style={{
                marginTop: "28px",
                width: "100%",
                padding: "14px",
                borderRadius: "10px",
                border: "none",
                background: "#2563eb",
                color: "white",
                fontSize: "16px",
                fontWeight: "bold",
                cursor: "pointer",
              }}
            >
              {questionIndex ===
              quizQuestions.length - 1
                ? "Finish Quiz"
                : "Next Question →"}
            </button>
          )}
        </div>
      </div>
    );
  }

  return (
    <div
      style={{
        minHeight: "100vh",
        background:
          "linear-gradient(135deg, #eef6ff, #ffffff)",
        padding: "40px 20px",
        fontFamily: "Arial, sans-serif",
      }}
    >
      <div
        style={{
          maxWidth: "1100px",
          margin: "0 auto",
        }}
      >
        <button
          onClick={goBack}
          style={{
            background: "transparent",
            border: "none",
            color: "#2563eb",
            cursor: "pointer",
            fontSize: "15px",
            marginBottom: "20px",
          }}
        >
          ← Back to Android Topics
        </button>

        <div
          style={{
            background: "white",
            borderRadius: "18px",
            padding: "32px",
            boxShadow:
              "0 8px 25px rgba(0,0,0,0.08)",
          }}
        >
          <div
            style={{
              display: "flex",
              justifyContent: "space-between",
              alignItems: "center",
              gap: "20px",
              flexWrap: "wrap",
            }}
          >
            <div>
              <h1
                style={{
                  color: "#1e3a8a",
                  marginBottom: "8px",
                }}
              >
                {activeTopic.title}
              </h1>

              <p
                style={{
                  color: "#6b7280",
                  margin: 0,
                }}
              >
                Lesson {activeTopicIndex + 1} of{" "}
                {subtopics.length}
              </p>
            </div>

            {completed.includes(activeTopic.id) && (
              <span
                style={{
                  background: "#dcfce7",
                  color: "#166534",
                  padding: "8px 14px",
                  borderRadius: "20px",
                  fontWeight: "bold",
                }}
              >
                ✓ Completed
              </span>
            )}
          </div>

          <div
            style={{
              marginTop: "25px",
              height: "9px",
              background: "#e5e7eb",
              borderRadius: "10px",
              overflow: "hidden",
            }}
          >
            <div
              style={{
                width: `${
                  ((activeTopicIndex + 1) /
                    subtopics.length) *
                  100
                }%`,
                height: "100%",
                background: "#2563eb",
              }}
            />
          </div>

          <section style={{ marginTop: "32px" }}>
            <h2 style={{ color: "#1e40af" }}>
              📖 Overview
            </h2>

            <p
              style={{
                color: "#374151",
                lineHeight: "1.8",
                fontSize: "16px",
              }}
            >
              {activeTopic.lesson.overview}
            </p>
          </section>

          {(activeTopic.lesson.sections || []).map(
            (section, index) => (
              <section
                key={`${section.heading}-${index}`}
                style={{
                  marginTop: "28px",
                  padding: "22px",
                  background: "#f8fbff",
                  borderRadius: "12px",
                  border: "1px solid #dbeafe",
                }}
              >
                <h3
                  style={{
                    color: "#1e40af",
                    marginTop: 0,
                  }}
                >
                  {section.heading}
                </h3>

                <p
                  style={{
                    color: "#374151",
                    lineHeight: "1.8",
                    marginBottom: 0,
                  }}
                >
                  {section.content}
                </p>
              </section>
            )
          )}

          <section style={{ marginTop: "30px" }}>
            <h2 style={{ color: "#1e40af" }}>
              ⚠️ Common Mistakes
            </h2>

            <ul
              style={{
                color: "#374151",
                lineHeight: "1.9",
                paddingLeft: "22px",
              }}
            >
              {(activeTopic.lesson.mistakes || []).map(
                (mistake, index) => (
                  <li key={`${mistake}-${index}`}>
                    {mistake}
                  </li>
                )
              )}
            </ul>
          </section>

          <div
            style={{
              marginTop: "32px",
              display: "flex",
              gap: "12px",
              flexWrap: "wrap",
            }}
          >
            <button
              onClick={startQuiz}
              style={{
                background: "#2563eb",
                color: "white",
                border: "none",
                padding: "13px 22px",
                borderRadius: "9px",
                fontWeight: "bold",
                cursor: "pointer",
              }}
            >
              📝 Take Quiz
            </button>

            {!completed.includes(activeTopic.id) && (
              <button
                onClick={markCompleted}
                style={{
                  background: "#16a34a",
                  color: "white",
                  border: "none",
                  padding: "13px 22px",
                  borderRadius: "9px",
                  fontWeight: "bold",
                  cursor: "pointer",
                }}
              >
                ✓ Mark Lesson Complete
              </button>
            )}
          </div>

          <div
            style={{
              marginTop: "35px",
              display: "flex",
              justifyContent: "space-between",
              gap: "12px",
            }}
          >
            <button
              onClick={() =>
                activeTopicIndex > 0 &&
                openTopic(activeTopicIndex - 1)
              }
              disabled={activeTopicIndex === 0}
              style={{
                padding: "12px 20px",
                borderRadius: "9px",
                border: "1px solid #bfdbfe",
                background:
                  activeTopicIndex === 0
                    ? "#f3f4f6"
                    : "white",
                color:
                  activeTopicIndex === 0
                    ? "#9ca3af"
                    : "#2563eb",
                cursor:
                  activeTopicIndex === 0
                    ? "not-allowed"
                    : "pointer",
              }}
            >
              ← Previous Lesson
            </button>

            <button
              onClick={() =>
                activeTopicIndex <
                  subtopics.length - 1 &&
                openTopic(activeTopicIndex + 1)
              }
              disabled={
                activeTopicIndex ===
                subtopics.length - 1
              }
              style={{
                padding: "12px 20px",
                borderRadius: "9px",
                border: "none",
                background:
                  activeTopicIndex ===
                  subtopics.length - 1
                    ? "#dbeafe"
                    : "#2563eb",
                color:
                  activeTopicIndex ===
                  subtopics.length - 1
                    ? "#93c5fd"
                    : "white",
                cursor:
                  activeTopicIndex ===
                  subtopics.length - 1
                    ? "not-allowed"
                    : "pointer",
              }}
            >
              Next Lesson →
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};

